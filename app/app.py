model=joblib.load(r"C:\Users\DELL\OneDrive\Documents\ML-Projects\house_price_prediction\models\xgboost_model.pkl")

st.title("🌴🏠🌴 California House Price Prediction")
st.divider()
st.write("Enter the district information below to predict the median house price.")

col1,col2=st.columns(2)

with col1:
    medinc=st.number_input(
    "Median Income(in tens of thousands of dollars)",
    min_value=0.0,
    value=3.5,
    step=0.1
)
    ave_rooms=st.number_input(
    "Average Rooms per Houselhold",
    min_value=0.0,
    value=5.0,
    step=0.1
    )
    population=st.number_input(
    "Population",
    min_value=1,
    value=1000
)
    latitude=st.number_input(
    "Latitude",
    value=34.0,
    step=0.01
)
    
with col2:
    house_age=st.number_input(
    "House Age(years)",
    min_value=1,
    value=25
)
    ave_bedrooms=st.number_input(
    "Average BedRooms per Household",
    min_value=0.0,
    value=5.0,
    step=0.1
)
    ave_occupancy=st.number_input(
    "Average Occupancy",
    min_value=0.0,
    value=3.0,
    step=0.1
)
    longitude=st.number_input(
        "Longitude",
        value=-118.0,
        step=0.01
    )

input_data=np.array([
    [
        medinc,
        house_age,
        ave_rooms,
        ave_bedrooms,
        population,
        ave_occupancy,
        latitude,
        longitude
    ]
])
st.divider()

if st.button("🔮 Estimate House Price"):
    prediction=model.predict(input_data)

    predicted_price=prediction[0]*100000

    st.metric(
        label="💰Predicted House Price",
        value=f"${predicted_price:,.2f}"
    )
    st.info("💡 This estimate was generated by an XGBoost model trained on the California Housing Dataset. ")

    with st.expander("📊 Why does the model make these predictions? "):

        st.write("""
This chart shows how much each feature contributed to the XGBoost model during training.

Higher importance indicates a greater influence on the model's predictions.
""")

        st.image(
           r"C:\Users\DELL\OneDrive\Documents\ML-Projects\house_price_prediction\images\feature_importance.png",
            caption="Feature Importance of the XGBoost Model",
            use_container_width=True
        )

st.divider()

